let currentLanguage = 'en';
const toggle = document.getElementById('languageToggle');

function applyLanguage(language) {
  const dictionary = translations[language];
  currentLanguage = language;
  document.documentElement.lang = language;
  document.documentElement.dir = language === 'ar' ? 'rtl' : 'ltr';
  document.body.setAttribute('dir', language === 'ar' ? 'rtl' : 'ltr');
  toggle.textContent = language === 'ar' ? 'English' : 'عربي';

  document.querySelectorAll('[data-i18n]').forEach((element) => {
    const key = element.getAttribute('data-i18n');
    if (dictionary[key]) {
      element.textContent = dictionary[key];
    }
  });
}

toggle.addEventListener('click', () => {
  applyLanguage(currentLanguage === 'en' ? 'ar' : 'en');
});

const imageDialog = document.getElementById('imageDialog');
const dialogImage = document.getElementById('dialogImage');
const closeDialog = document.getElementById('closeDialog');

document.querySelectorAll('[data-preview]').forEach((button) => {
  button.addEventListener('click', () => {
    dialogImage.src = button.getAttribute('data-preview');
    if (typeof imageDialog.showModal === 'function') {
      imageDialog.showModal();
    }
  });
});

closeDialog.addEventListener('click', () => imageDialog.close());
imageDialog.addEventListener('click', (event) => {
  if (event.target === imageDialog) imageDialog.close();
});

applyLanguage('en');
